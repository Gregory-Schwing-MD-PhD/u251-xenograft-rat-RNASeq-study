#!/usr/bin/env python
r"""Write generated/numbers.tex from the results files, so the manuscript compiles from them.

THE CONTRACT (Greg, 2026-09-27, carried over from the RSNA AI manuscript's tools/results_macros.py): the paper's
numbers must come from a reproducible, auditable pipeline, not from prose typed by hand. numbers_manifest.json
names, for every result the manuscript quotes, the results file, a JSON pointer into it (RFC 6901), a format, and
the grid job that produced the file. This tool runs at every build:

  * a key whose file and pointer resolve becomes  \expandafter\def\csname noa@val@KEY\endcsname{VALUE}
    plus \noa@src@KEY (file#pointer); the audit table records the value, the file's SHA-256 and the time;
  * a key whose file or pointer does not exist becomes \noa@pend@KEY{JOB} and the manuscript prints
    "XXX Result Pending-JOB" in red at that spot, so a pending number is visible on the page and in the PDF;
  * figures are the same: \noa@fig@KEY (path) and \noa@figjob@KEY (job).

`--check` exits 1 while any key is pending, or any key defined in the manifest is unused by the tex, or any bare
result-looking number sits in the Abstract or Results outside a macro. Nothing here invents a value: a missing file
is reported as missing.

    python tools/results_macros.py            # write generated/numbers.tex + generated/numbers_audit.md
    python tools/results_macros.py --check    # also audit the tex; exit 1 on any pending/unused/bare number
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "numbers_manifest.json"
GEN = ROOT / "generated"
TEX_FILES = ["main.tex"] + [f"sections/{p.name}" for p in sorted((ROOT / "sections").glob("*.tex"))]


def json_pointer(doc, pointer: str):
    """RFC 6901: '' is the whole document; '/a/0/b~1c' walks keys and list indexes ('~1' = '/', '~0' = '~')."""
    if pointer in ("", "/"):
        return doc
    cur = doc
    for raw in pointer.lstrip("/").split("/"):
        tok = raw.replace("~1", "/").replace("~0", "~")
        if isinstance(cur, list):
            cur = cur[int(tok)]
        elif isinstance(cur, dict):
            cur = cur[tok]
        else:
            raise KeyError(tok)
    return cur


def fmt_value(v, fmt: str | None, kind: str | None):
    if kind == "kn":                          # {"k": 56, "n": 59} or [56, 59] -> "56/59"
        k, n = (v["k"], v["n"]) if isinstance(v, dict) else (v[0], v[1])
        return f"{int(k)}/{int(n)}"
    if kind == "k_of_n":                      # -> "56 of 59", the prose form
        k, n = (v["k"], v["n"]) if isinstance(v, dict) else (v[0], v[1])
        return f"{int(k)} of {int(n):,}"
    if kind == "ci":                          # [lo, hi] -> "[lo, hi]"
        f = fmt or "{:.2f}"
        return "[" + f.format(float(v[0])).rstrip("%") + ", " + f.format(float(v[1])).rstrip("%") + "]"
    if kind == "ci_bare":                     # [lo, hi] -> "lo, hi" (the prose writes the brackets)
        f = fmt or "{:.2f}"
        return f.format(float(v[0])).rstrip("%") + " to " + f.format(float(v[1])).rstrip("%")
    if kind == "p":                           # journal form: "<.001", else "=.05" (no leading zero)
        x = float(v)
        return "<.001" if x < 0.001 else "=" + f"{x:.2f}".lstrip("0")
    if kind == "pct_of":                      # a fraction 0-1 -> percent
        return (fmt or "{:.1f}").format(100.0 * float(v))
    if kind == "num":                         # a value that arrives as a string (every TSV cell does)
        return (fmt or "{:.2f}").format(float(v))
    if kind == "int":
        return f"{int(float(v)):,}"
    if kind == "rank_of":                     # {"rank": 1, "n": 20} -> "1 of 20"
        return f"{int(v['rank'])} of {int(v['n'])}"
    if kind == "count":                       # a list or dict -> its length (e.g. how many exclusion lists)
        return str(len(v))
    if fmt:
        return fmt.format(v)
    if isinstance(v, float):
        return f"{v:.2f}"
    return str(v)


def tex_escape(s: str) -> str:
    return s.replace("\\", "/").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#").replace("&", r"\&")


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def resolve(manifest: dict):
    lines, audit, pending = [], [], []
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines.append(f"% generated by tools/results_macros.py at {now}; do not edit -- edit numbers_manifest.json")
    for key, spec in manifest.get("numbers", {}).items():
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", key):
            raise SystemExit(f"bad key {key!r}: letters, digits and underscores only")
        f = ROOT / spec["file"]
        job = str(spec.get("job", "no-job-recorded"))
        src = f"{spec['file']}#{spec.get('pointer', '')}"
        try:
            doc = json.load(open(f, encoding="utf-8"))
            val = fmt_value(json_pointer(doc, spec.get("pointer", "")), spec.get("fmt"), spec.get("kind"))
        except FileNotFoundError:
            pending.append((key, job, "file missing", src)); val = None
        except (KeyError, IndexError, TypeError, ValueError) as e:
            pending.append((key, job, f"pointer failed ({type(e).__name__}: {e})", src)); val = None
        if val is None:
            lines.append(f"\\expandafter\\def\\csname noa@pend@{key}\\endcsname{{{tex_escape(job)}}}")
            continue
        # the value is TeX text: a bare % would comment out the closing brace, so escape every special
        lines.append(f"\\expandafter\\def\\csname noa@val@{key}\\endcsname{{{tex_escape(str(val))}}}")
        lines.append(f"\\expandafter\\def\\csname noa@src@{key}\\endcsname{{{tex_escape(src)}}}")
        audit.append((key, val, src, sha256(f), spec.get("note", "")))
    for key, spec in manifest.get("figures", {}).items():
        f = ROOT / spec["file"]
        job = str(spec.get("job", "no-job-recorded"))
        lines.append(f"\\expandafter\\def\\csname noa@fig@{key}\\endcsname{{{spec['file']}}}")
        lines.append(f"\\expandafter\\def\\csname noa@figjob@{key}\\endcsname{{{tex_escape(job)}}}")
        if f.exists():
            audit.append((key, "(figure)", spec["file"], sha256(f), spec.get("note", "")))
        else:
            pending.append((key, job, "figure file missing", spec["file"]))
    return lines, audit, pending, now


def tex_uses(keys: set[str]) -> dict[str, int]:
    used = {k: 0 for k in keys}
    pat = re.compile(r"\\RESULT(?:FIG|SAY|STATUS)?(?:\[[^\]]*\])?\{([A-Za-z][A-Za-z0-9_]*)\}")
    for rel in TEX_FILES:
        p = ROOT / rel
        if not p.exists():
            continue
        for m in pat.finditer(p.read_text(encoding="utf-8", errors="replace")):
            if m.group(1) in used:
                used[m.group(1)] += 1
    return used


def bare_numbers(section_files: list[str]) -> list[tuple[str, int, str]]:
    """Result-looking numerals in the sections that may only quote results. Years, figure and table numbers, and
    reference marks are not results and are skipped by the pattern."""
    hits = []
    pat = re.compile(r"(?<![A-Za-z\\{])(\d{1,3}(?:,\d{3})*(?:\.\d+)?\s*(?:\\%|%|/\s*\d|\s*\[\d))")
    for rel in section_files:
        p = ROOT / rel
        if not p.exists():
            continue
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            s = line.strip()
            if s.startswith("%"):
                continue
            s = re.sub(r"\\RESULT[A-Z]*(?:\[[^\]]*\])?\{[^}]*\}", " ", s)
            s = re.sub(r"\\PENDING(?:FIG)?\{[^}]*\}(?:\{[^}]*\})?", " ", s)
            for m in pat.finditer(s):
                hits.append((rel, i, m.group(1).strip()))
    return hits


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--sections", nargs="*", default=["sections/results.tex", "sections/abstract.tex"],
                    help="tex files in which every result number must be a macro")
    a = ap.parse_args()
    manifest = json.load(open(MANIFEST, encoding="utf-8"))
    lines, audit, pending, now = resolve(manifest)
    GEN.mkdir(exist_ok=True)
    (GEN / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    with open(GEN / "numbers_audit.md", "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# Numbers the manuscript compiles from ({now})\n\nGenerated by tools/results_macros.py from "
                f"numbers_manifest.json. Every value below is read from the named file at build time; the file is a "
                f"byte copy of a grid output and the job that wrote it is named.\n\n")
        f.write("| key | value | source (file#pointer) | sha256 of file | job / note |\n|---|---|---|---|---|\n")
        for key, val, src, sha, note in audit:
            f.write(f"| `{key}` | {val} | `{src}` | `{sha[:16]}` | {note} |\n")
        f.write("\n## Pending\n\n| key | job | why | source |\n|---|---|---|---|\n")
        for key, job, why, src in pending:
            f.write(f"| `{key}` | {job} | {why} | `{src}` |\n")
    json.dump({"generated": now, "resolved": [k for k, *_ in audit],
               "pending": [{"key": k, "job": j, "why": w, "source": s} for k, j, w, s in pending]},
              open(GEN / "pending.json", "w", encoding="utf-8"), indent=1)
    print(f"numbers.tex: {len(audit)} resolved, {len(pending)} pending -> {GEN}")
    for key, job, why, src in pending:
        print(f"   PENDING {key}: job {job} ({why}) {src}")
    if not a.check:
        return 0
    rc = 0
    used = tex_uses(set(manifest.get("numbers", {})) | set(manifest.get("figures", {})))
    unused = [k for k, n in used.items() if n == 0]
    if unused:
        rc = 1
        print(f"UNUSED manifest keys ({len(unused)}): " + ", ".join(unused[:20]) + (" ..." if len(unused) > 20 else ""))
    bare = bare_numbers(a.sections)
    if bare:
        rc = 1
        print(f"BARE result-looking numbers outside a macro ({len(bare)}):")
        for rel, i, s in bare[:20]:
            print(f"   {rel}:{i}: {s}")
    if pending:
        rc = 1
        print(f"{len(pending)} key(s) still pending")
    return rc


if __name__ == "__main__":
    sys.exit(main())
